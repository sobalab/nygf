// Builds the admin's product list from the catalogue, at build time.
//
// The admin surface must not import app/catalogue-data.ts at run time. That file
// runs two invariants as it loads and throws on either — a duplicate slug, a
// colour word matching no chip — which is exactly right while only prerendered
// pages import it, because the failure lands in the build. Pull it into a Server
// Action or an admin page and the same throw lands in a request instead, and a
// mistyped colour takes the cooler screen down at six in the morning.
//
// So the catalogue is read here, once, and written out flat. Names, slugs and
// category labels only: no prose, no photography, nothing the shop edits in the
// file. Run it whenever the catalogue changes.
//
//   npm run sync:products
//
// The real version of this also diffs against the products table and refuses to
// write on a slug that has stock behind it — see the plan. This much is what the
// prototype needs.

import { writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const { flowers } = await import(path.join(root, "app/catalogue-data.ts"));

const rows = flowers.map((flower) => ({
  slug: flower.slug,
  name: flower.name,
  category: flower.group,
}));

const out = `// Generated by scripts/sync-products.mjs. Do not edit.
// Source of truth is app/catalogue-data.ts; run \`npm run sync:products\` after
// changing it. Flat on purpose — see the note in the script for why admin does
// not import the catalogue directly.
export type CatalogueProduct = { slug: string; name: string; category: string };

export const catalogueProducts: CatalogueProduct[] = ${JSON.stringify(rows, null, 2)};
`;

const target = path.join(root, "app/admin/catalogue-products.ts");
writeFileSync(target, out);
console.log(`Wrote ${rows.length} products to app/admin/catalogue-products.ts`);
